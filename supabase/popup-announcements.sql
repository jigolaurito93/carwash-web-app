-- Feature patch for an existing database. New projects should run schema.sql instead.
-- Popup announcements: separate table from the top-bar site_announcements.
-- Run once in the Supabase SQL editor (or re-run; policies are replaced).
-- After this, run `pnpm gen:types`.

create table if not exists public.popup_announcements (
  id bigint generated by default as identity primary key,
  title text,
  message text,
  link_url text,
  kind text not null default 'notice',
  layout_key text not null default 'default',
  starts_at timestamptz,
  expires_at timestamptz,
  closes_on date,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint popup_announcements_kind_check
    check (kind in ('notice', 'promo', 'closure'))
);

create index if not exists popup_announcements_sort_order_idx
  on public.popup_announcements (sort_order, id);

alter table public.popup_announcements enable row level security;

drop policy if exists "Public can view active popup announcements" on public.popup_announcements;
create policy "Public can view active popup announcements"
  on public.popup_announcements
  for select
  to anon, authenticated
  using (
    is_active = true
    and (starts_at is null or starts_at <= now())
    and (expires_at is null or expires_at > now())
  );

drop policy if exists "Authenticated can view all popup announcements" on public.popup_announcements;
create policy "Authenticated can view all popup announcements"
  on public.popup_announcements
  for select
  to authenticated
  using (true);

drop policy if exists "Authenticated can insert popup announcements" on public.popup_announcements;
create policy "Authenticated can insert popup announcements"
  on public.popup_announcements
  for insert
  to authenticated
  with check (true);

drop policy if exists "Authenticated can update popup announcements" on public.popup_announcements;
create policy "Authenticated can update popup announcements"
  on public.popup_announcements
  for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists "Authenticated can delete popup announcements" on public.popup_announcements;
create policy "Authenticated can delete popup announcements"
  on public.popup_announcements
  for delete
  to authenticated
  using (true);

grant select on table public.popup_announcements to anon, authenticated;
grant insert, update, delete on table public.popup_announcements to authenticated;

-- Copy existing modal rows so the public popup keeps working after the split.
insert into public.popup_announcements (
  title,
  message,
  link_url,
  kind,
  layout_key,
  starts_at,
  expires_at,
  closes_on,
  sort_order,
  is_active
)
select
  title,
  message,
  link_url,
  kind,
  'default',
  starts_at,
  expires_at,
  closes_on,
  sort_order,
  coalesce(is_active, false)
from public.site_announcements
where show_as_modal = true
  and not exists (
    select 1
    from public.popup_announcements as existing
    where existing.message is not distinct from site_announcements.message
      and existing.title is not distinct from site_announcements.title
      and existing.expires_at is not distinct from site_announcements.expires_at
  );
